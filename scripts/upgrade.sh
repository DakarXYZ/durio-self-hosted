#!/usr/bin/env bash
# Upgrade the stack to another image tag (SH-07):
#
#   scripts/upgrade.sh <tag> [--pin-digests] [--skip-smoke] [--yes]     e.g. 0.16.0-fork.2
#
# preflight -> local mongodump (ALWAYS, backups/pre-upgrade, last 3 kept) -> full backup if
# BACKUP_ENABLED=true -> pull -> pending migrations/*.sh -> up api (runs DB migrations) ->
# health -> up the rest -> health -> smoke.sh.
# --pin-digests writes images.lock.env (sha256 digests of the tag); an existing lock is always
# refreshed for the new tag. On failure: automatic rollback of the tag only if the database
# migration revision did not change; otherwise services are stopped and restore steps printed.
set -Eeuo pipefail
# shellcheck source=scripts/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_cmd docker jq
require_config

NEW_TAG='' PIN=0 SKIP_SMOKE=0 YES=0
while [[ $# -gt 0 ]]; do
    case $1 in
        --pin-digests) PIN=1 ;;
        --skip-smoke) SKIP_SMOKE=1 ;;
        --yes | -y) YES=1 ;;
        -h | --help) sed -n '2,12p' "$0"; exit 0 ;;
        -*) die "unknown option $1" ;;
        *) NEW_TAG=$1 ;;
    esac
    shift
done
[[ -n $NEW_TAG ]] || die "usage: $0 <tag> [--pin-digests] [--skip-smoke] [--yes]"
[[ $NEW_TAG =~ ^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$ ]] || die "invalid tag: $NEW_TAG"
[[ $NEW_TAG != latest ]] || die "refusing 'latest': use a release tag"
cd "$ROOT"

DATE=$(date -u +%Y%m%dT%H%M%SZ)
mkdir -p logs
LOG="logs/upgrade-$DATE.log"
exec > >(tee -a "$LOG") 2>&1

OLD_TAG=$(env_get APP_TAG .env)
REGISTRY=$(env_get IMAGE_REGISTRY .env)
info "upgrade $OLD_TAG -> $NEW_TAG (log: $LOG)"
warn_no_backups
if [[ $YES -eq 0 && -t 0 ]]; then
    read -rp "Continue? [y/N]: " reply
    [[ $reply == [yY] ]] || die "aborted"
fi

"$ROOT/scripts/preflight.sh"

# 1. Backups: the local dump is mandatory (rollback of DB migrations needs it).
dump="backups/pre-upgrade/$DATE-$OLD_TAG.archive.gz"
"$ROOT/scripts/backup.sh" --mongo-dump "$dump"
# shellcheck disable=SC2012 # our own file names, sorted by mtime
mapfile -t old_dumps < <(ls -1t backups/pre-upgrade/*.archive.gz 2>/dev/null | tail -n +4)
[[ ${#old_dumps[@]} -eq 0 ]] || rm -f -- "${old_dumps[@]}"
if backups_enabled; then
    "$ROOT/scripts/backup.sh"
fi

revision() {
    mongo_eval 'const m = db.getSiblingDB("revolt").migrations.findOne({_id: 0}); print(m ? m.revision : 0)' |
        tail -n 1
}
REV_BEFORE=$(revision)
info "database migration revision before: $REV_BEFORE"

# 2. New tag (+ digests).
cp -p .env ".env.$DATE.bak"
env_set APP_TAG "$NEW_TAG" .env
if [[ $PIN -eq 1 || -f images.lock.env ]]; then
    [[ -n $REGISTRY ]] || die "--pin-digests needs a registry (IMAGE_REGISTRY in .env)"
    [[ -f images.lock.env ]] && cp -p images.lock.env "images.lock.env.$DATE.bak"
    info "resolving digests for $NEW_TAG"
    lock_tmp=$(mktemp)
    echo "# Generated by scripts/upgrade.sh for $NEW_TAG — image digests (value includes '@')." >"$lock_tmp"
    for image in api events file-server proxy gifbox crond pushd voice-ingress; do
        digest=$(docker buildx imagetools inspect --format '{{json .Manifest}}' "${REGISTRY}durio-$image:$NEW_TAG" |
            jq -r '.digest')
        [[ $digest == sha256:* ]] || die "no digest for durio-$image:$NEW_TAG"
        var=$(printf '%s' "$image" | tr '[:lower:]-' '[:upper:]_')
        echo "${var}_DIGEST=@$digest" >>"$lock_tmp"
    done
    mv "$lock_tmp" images.lock.env
fi

rollback() {
    local rev_after
    rev_after=$(revision || echo unknown)
    warn "upgrade failed (revision before $REV_BEFORE, after $rev_after)"
    if [[ $rev_after == "$REV_BEFORE" ]]; then
        warn "no database migration ran: rolling back to $OLD_TAG"
        cp -p ".env.$DATE.bak" .env
        [[ -f images.lock.env.$DATE.bak ]] && cp -p "images.lock.env.$DATE.bak" images.lock.env
        compose up -d || true
        compose up -d --force-recreate caddy || true
        die "rolled back to $OLD_TAG — see $LOG"
    fi
    compose stop "${BACKEND_SERVICES[@]}" gifbox caddy || true
    warn "database migrations already ran: NOT rolling back images silently. Services are stopped."
    warn "Either fix forward (scripts/compose logs api), or restore the pre-upgrade dump:"
    warn "  cp .env.$DATE.bak .env && scripts/restore.sh --from-archive $dump && scripts/compose up -d"
    die "upgrade failed — see $LOG"
}

# 3. Pull + pending migration scripts (idempotent, recorded in data/.applied-migrations).
compose pull --quiet || rollback
touch data/.applied-migrations
for m in migrations/[0-9]*.sh; do
    [[ -e $m ]] || continue
    name=$(basename "$m")
    grep -qxF "$name" data/.applied-migrations && continue
    info "migration $name"
    bash "$m" || rollback
    echo "$name" >>data/.applied-migrations
done

# 4. api first: only api runs DB migrations; new EventV1 stay behind features.e2ee (C19).
compose up -d api || rollback
wait_healthy 600 api || rollback
compose up -d --remove-orphans || rollback
# The Caddyfile is a single-file bind mount: a git checkout replaces the file, the running caddy
# keeps the old one (and the image did not change, so `up -d` leaves it alone)
compose up -d --force-recreate caddy || rollback
services=$(compose config --services)
# shellcheck disable=SC2046 # word splitting intended
wait_healthy 300 $(grep -vxE 'database-init|createbuckets' <<<"$services") || rollback

info "migration revision after: $(revision)"

if [[ $SKIP_SMOKE -eq 0 ]]; then
    expect=${NEW_TAG/-fork/+fork}
    if [[ $expect == *+fork* ]]; then
        "$ROOT/scripts/smoke.sh" --expect-version "$expect" || rollback
    else
        "$ROOT/scripts/smoke.sh" || rollback
    fi
fi
info "upgrade to $NEW_TAG done"
warn_no_backups
